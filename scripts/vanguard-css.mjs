// Builds vanguard/vanguard.css from vanguard/styles.css (the ERP team's stylesheet, kept as delivered).
// Vanguard was written as a page of its own; inside BUMEX One its rules must stay inside the .vanguard container:
// - page rules (:root, html, body, #root) apply to the container; every other selector is prefixed with it;
// - keyframes get a vg- prefix so they cannot collide with the app's;
// - BUMEX One's base reset (Tailwind preflight) is undone inside the container, as Vanguard was designed on the
//   browser's defaults;
// - BUMEX One's pages shown in Vanguard's frame (.bumex-page, components/vanguard/vanguard-shell.tsx) are left out of
//   every rule: they keep BUMEX One's own styles.
//
//   node scripts/vanguard-css.mjs      (run again after a new delivery of styles.css)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const SCOPE = ".vanguard";
// zero specificity, so the cascade between Vanguard's rules is unchanged
const OUTSIDE_PAGES = ":not(:where(.bumex-page, .bumex-page *))";

// `.vanguard x` → `.vanguard x:not(…)`, the exclusion before any pseudo-element (::before, ::placeholder…)
const outsidePages = (selector) => {
  const at = selector.search(/::/);
  return at === -1 ? `${selector}${OUTSIDE_PAGES}` : `${selector.slice(0, at)}${OUTSIDE_PAGES}${selector.slice(at)}`;
};
const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "vanguard");
const source = readFileSync(join(dir, "styles.css"), "utf8");
const root = postcss.parse(source);

const keyframes = new Set();
root.walkAtRules(/keyframes$/, (at) => {
  keyframes.add(at.params);
  at.params = `vg-${at.params}`;
});
root.walkDecls(/^animation(-name)?$/, (decl) => {
  decl.value = decl.value
    .split(",")
    .map((part) => part.trim().split(/\s+/).map((token) => (keyframes.has(token) ? `vg-${token}` : token)).join(" "))
    .join(", ");
});

const scope = (selector) => {
  const s = selector.trim();
  if ([":root", "html", "body", "#root"].includes(s)) return SCOPE;
  if (s === "*") return outsidePages(`${SCOPE} *`);
  if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)/, SCOPE);
  return outsidePages(`${SCOPE} ${s}`);
};
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = [...new Set(rule.selectors.map(scope))];
});

// Browser defaults back inside Vanguard. Unlayered rules beat Tailwind's @layer base; :where() keeps them below every
// Vanguard rule, so Vanguard's own declarations still win wherever it sets something.
const undoPreflight = `
${SCOPE} :where(*) { margin: revert; padding: revert; border: revert; }
${SCOPE} :where(h1, h2, h3, h4, h5, h6) { font-size: revert; font-weight: revert; }
${SCOPE} :where(a) { color: revert; text-decoration: revert; }
${SCOPE} :where(b, strong) { font-weight: revert; }
${SCOPE} :where(code, kbd, samp, pre) { font-family: revert; font-size: revert; }
${SCOPE} :where(small) { font-size: revert; }
${SCOPE} :where(table) { text-indent: revert; border-color: revert; border-collapse: revert; }
${SCOPE} :where(ol, ul, menu) { list-style: revert; }
${SCOPE} :where(img, svg, video, canvas, audio, iframe, embed, object) { display: revert; vertical-align: revert; }
${SCOPE} :where(img, video) { max-width: revert; height: revert; }
${SCOPE} :where(button, input, select, optgroup, textarea) { font: revert; font-feature-settings: revert; font-variation-settings: revert; letter-spacing: revert; color: revert; border-radius: revert; background-color: revert; opacity: revert; }
${SCOPE} :where(button, input[type="button"], input[type="reset"], input[type="submit"]) { appearance: revert; }
${SCOPE} :where(textarea) { resize: revert; }
${SCOPE} :where(hr) { height: revert; color: revert; border-top-width: revert; }
${SCOPE} :where(summary) { display: revert; }
${SCOPE} ::placeholder { opacity: revert; color: revert; }
/* The container covers the window, like the page Vanguard was. It keeps the browser's light form controls and text
   rendering whatever theme BUMEX One puts on the page. */
${SCOPE} { position: fixed; inset: 0; text-rendering: auto; color-scheme: light; }
`;

const undo = postcss.parse(undoPreflight);
undo.walkRules((rule) => {
  rule.selectors = rule.selectors.map((selector) => (selector.trim() === SCOPE ? selector : outsidePages(selector)));
});

const header = `/* GENERATED by scripts/vanguard-css.mjs from vanguard/styles.css — do not edit by hand. */\n`;
writeFileSync(join(dir, "vanguard.css"), header + undo.toString() + "\n" + root.toString());
console.log(`vanguard.css written · ${keyframes.size} keyframes renamed`);
