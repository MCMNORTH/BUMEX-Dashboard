function translate(message: string): string | null {
  const exact = EXACT[message];
  if (exact !== undefined) return exact;
  for (const [pattern, english] of RULES) {
    const match = pattern.exec(message);
    if (match) return typeof english === 'string' ? message.replace(pattern, english) : english(...match.slice(1));
  }
  return null;
}

/** An engine's refusal (a French sentence) in English; a sentence nobody listed is returned as it is. */
export function englishMessage(message: string): string {
  const whole = translate(message);
  if (whole !== null) return whole;
  // the posting checks, joined by the engine (ledger.ts postEntry): each one on its own
  if (message.includes(' · ')) return message.split(' · ').map((part) => translate(part) ?? part).join(' · ');
  return message;
}
